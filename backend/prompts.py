"""Промпты для генерации ответов."""

SYSTEM_RAG = """Ты — ассистент, отвечающий строго по предоставленным фрагментам.
Если ответа в них нет — скажи «В предоставленных источниках нет информации».
Не выдумывай факты. Источники перечислять не надо — они придут отдельно.
Отвечай кратко и по существу, используя информацию из контекста."""

SYSTEM_EXTRACTIVE = """Ты — ассистент, который извлекает информацию из предоставленных фрагментов.
Составь ответ на основе наиболее релевантных частей текста.
Если в фрагментах нет ответа — честно скажи об этом.
Не добавляй информацию извне."""


def build_context(chunks: list[dict]) -> str:
    """
    Построить контекст из чанков для промпта.
    Формат: [1] текст\n\n[2] текст...
    """
    parts = []
    for i, chunk in enumerate(chunks, 1):
        text = chunk.get("text", "").strip()
        if text:
            parts.append(f"[{i}] {text}")
    return "\n\n".join(parts)


def build_user_prompt(question: str, context: str) -> str:
    """Построить пользовательский промпт с контекстом."""
    return f"""Контекст:
{context}

Вопрос: {question}

Ответ:"""


def build_extractive_prompt(question: str, chunks: list[dict]) -> str:
    """Построить промпт для extractive fallback."""
    context = build_context(chunks)
    return f"""Извлеки ответ на вопрос из следующих фрагментов:

{context}

Вопрос: {question}

Если в фрагментах нет ответа, скажи: "В предоставленных источниках нет информации."
Если есть — составь краткий ответ на основе фрагментов."""
